# 1-15 第③圈的參考答案（老師端也用它驗證壞版本）
from share import shares

t = {"餐飲": 160, "交通": 100, "娛樂": 40}
r = shares(t)
# 每一類＝小計 ÷ 全部 × 100，留到小數一位（要有小數的例子，才看得出有沒有留到小數一位）
assert r == {"餐飲": 53.3, "交通": 33.3, "娛樂": 13.3}
# 不能動到原本的 totals
assert t == {"餐飲": 160, "交通": 100, "娛樂": 40}
# 花 0 元的分類也要有，是 0.0
assert shares({"餐飲": 50, "醫療": 0}) == {"餐飲": 100.0, "醫療": 0.0}
# 剛好整除的例子
assert shares({"餐飲": 300, "交通": 100}) == {"餐飲": 75.0, "交通": 25.0}
# 加總要顯示 100%：正確版是 99.9，需求沒說少掉的 0.1 要給誰
assert round(sum(r.values()), 1) == 100  # 需求有問題
