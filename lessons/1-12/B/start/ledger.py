# 1. 先問預算：提示字寫「預算：」，打一個整數。
# 2. 接着一直問，打 q 就停：
#      先問「分類，打 q 結束：」，再問「金額：」（打一個整數）
#    分類打「飲食」就加進飲食的小計，打「娛樂」就加進娛樂的小計，打別的字都加進「其他」。
# 3. 打 q 以後，印出三個小計和合計（一行一個）：
#      飲食 ○○ 元
#      娛樂 ○○ 元
#      其他 ○○ 元
#      合計 ○○ 元
# 4. 再印一行預算燈號：合計低於預算的 80% 印「綠燈」；80% 到 100%（剛好 100% 也算）印「黃燈」；超過預算印「紅燈」。
# 5. 最後問「幾個人分：」（打一個整數），印出每個人先付多少、剩下的零頭幾元：
#      每人 ○○ 元，零頭 ○ 元
#
