# 1-20 第③圈：老師的標準檢查（跟影片裡熊寫的三條一樣）
from top3 import top3

# 同一類的兩筆要加起來
assert top3([("餐", 120), ("餐", 85)]) == [("餐", 205)]
# 四類，同一類好幾筆、金額有大有小：先加總、從大排到小、只留前三類
assert top3([("餐", 120), ("書", 450), ("餐", 300), ("車", 30), ("衣", 60)]) == [("書", 450), ("餐", 420), ("衣", 60)]
# 空的 list：交回空的 list
assert top3([]) == []
