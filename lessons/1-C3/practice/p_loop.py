# 矯正包練習：迴圈裡的 if 和 append，誰縮在誰底下（1-17）
# 這支應該印出下面三行，可是有一行縮排錯了：
#   大於 100： 120
#   大於 100： 300
#   一共 2 筆大於 100
# 先不要跑。在紙上寫下它現在會印出什麼，再跑一次對答案：uv run lessons/1-C3/practice/p_loop.py
# 再把縮排錯的那一行改好（只改縮排，不改字），存檔再跑，要印出上面那三行。
amounts = [120, 80, 300, 95]
big = []
for a in amounts:
    if a > 100:
        print("大於 100：", a)
    big.append(a)
print("一共", len(big), "筆大於 100")
