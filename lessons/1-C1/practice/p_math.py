# 矯正包練習：/、//、%、**、先算哪一個（1-4）
# 先不要跑。每一行會印出什麼？在紙上寫下來。
#   /  一般的除，答案是小數          //  除完只留整數（往比較小的那邊取）
#   %  除完剩多少（餘數）            **  次方
#   先算哪一個：括號 → 次方 → 負號 → 乘、除、//、% → 加、減
# 寫好再在帳本資料夾打 uv run lessons/1-C1/practice/p_math.py 對答案。
print(17 / 4)
print(17 // 4)
print(17 % 4)
print(-17 // 4)
print(2 ** 5)
print(10 + 2 * 3)
print((10 + 2) * 3)
print(-3 ** 2)
