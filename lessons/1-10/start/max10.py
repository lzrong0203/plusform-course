# 1-10 第②圈：用「帶我寫」，跟家教一起把記帳程式改成「最多記 10 筆」
#
# 要求：
#   1. 最多記 10 筆；記滿 10 筆，就算沒打 q 也自己停下來
#   2. 打 q 可以提早結束；空白的一行（多按一下 Enter）跳過，也不算一筆
#   3. 最後印出一共幾筆、合計多少，例如：一共 2 筆，合計 205 元
#
# 做法：在家教專案裡打「帶我寫：……」，每一步你先說要做什麼，家教才給那一步的寫法（0-8 教過）。
# 你說了什麼、家教給了什麼，記在 lead.md。
# 下面是第①圈的記帳程式，從這裡開始改：

total = 0
while True:
    text = input("金額，打 q 結束：")
    if text == "q":
        break
    if text == "":
        continue
    total = total + int(text)
print("一共", total, "元")
